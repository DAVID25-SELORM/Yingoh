// Generates (1) a clinician review sheet and (2) a DRAFT-ONLY import script for the Part B-D questions.
//   node scripts/build-diagnostic-content.mjs        writes both files next to the content module
// Nothing is applied to any database by this script.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { ITEMS, PLAN, SOURCE_BATCH } from '../diagnostic-content/parts-b-d.mjs';

const dollar = text => {
  if (text.includes('$q$')) throw new Error('content must not contain the $q$ delimiter');
  return `$q$${text}$q$`;
};
const NOTE = 'DRAFT for clinical review. Requires an approving clinical reviewer and structured references before publication.';

export function buildImportSql(items = ITEMS) {
  const rows = items.map(item => {
    const choices = JSON.stringify(item.choices.map(({ id, text }) => ({ id, text })));
    const answer = JSON.stringify({ ids: item.correct });
    const explanations = JSON.stringify(item.option_explanations);
    const notes = `${NOTE} Diagnostic ${item.id} (Part ${item.part}); intended difficulty ${item.difficulty}; subtopic: ${item.subtopic}.`;
    return `insert into public.questions(topic,question_type,prompt,choices,correct_answer,rationale,status,client_need,clinical_judgment,clinical_review_status,source_batch,quality_notes,correct_answer_explanation,option_explanations)
select ${dollar(item.topic)},${dollar(item.type)},${dollar(item.prompt)},${dollar(choices)}::jsonb,${dollar(answer)}::jsonb,${dollar(item.rationale)},'draft',${dollar(item.subcategory)},${dollar(item.cj_step)},'pending',${dollar(SOURCE_BATCH)},${dollar(notes)},${dollar(item.correct_answer_explanation)},${dollar(explanations)}::jsonb
where not exists(select 1 from public.questions q where q.prompt=${dollar(item.prompt)});`;
  });
  return `-- NurseFaculty SMART diagnostic, Parts B-D: ${items.length} DRAFT questions (batch ${SOURCE_BATCH}).
-- Generated by scripts/build-diagnostic-content.mjs. Idempotent: a question whose prompt already exists is skipped.
-- Rows are inserted as status='draft', clinical_review_status='pending', so they cannot appear in any diagnostic form
-- or practice pool until a clinical reviewer approves them (Content Review screen / review_question).
-- Review requires structured references (title, organization, HTTPS URL, accessed date), which reviewers add themselves.
begin;
${rows.join('\n\n')}
commit;
`;
}

export function buildReviewSheet(items = ITEMS) {
  const label = id => id.toUpperCase();
  const head = `# Diagnostic Parts B–D: clinical review sheet

**Batch:** \`${SOURCE_BATCH}\` · **Status:** DRAFT, not yet reviewed · **Items:** ${items.length}

These questions were drafted for the NurseFaculty SMART NCLEX Roadmap diagnostic. They are **not** clinically approved. A licensed nurse educator
must review every item against current guidelines before it is published. Nothing here has been imported into any database.

## Coverage

| Part | Items | Focus |
| --- | ---: | --- |
| B | ${PLAN.parts.B} | Clinical judgment (Analyze Cues 10, Prioritize Hypotheses 10, Recognize Cues 3, Generate Solutions 3, Take Action 2, Evaluate Outcomes 2) |
| C | ${PLAN.parts.C} | Medication calculations (all independently recomputed by an automated check) |
| D | ${PLAN.parts.D} | Prioritization and delegation |

## How to review each item
- [ ] The keyed answer is the single best answer (or the exact correct set for select-all) under current NCLEX-RN / practice guidelines.
- [ ] Every distractor is plausible but clearly worse, and its explanation is accurate.
- [ ] Cues in the stem are realistic and sufficient; no unnecessary clues to the answer.
- [ ] Wording is clear, free of bias, and uses standard values (units, ranges).
- [ ] For calculations: recompute by hand and confirm rounding rules.
- [ ] Add at least one structured reference (title, organization, HTTPS URL, accessed date). Approve or request changes.

---

`;
  const body = items.map(item => {
    const opts = item.choices.map(c => `- ${label(c.id)}. ${c.text}${item.correct.includes(c.id) ? '  **✓ correct**' : ''}`).join('\n');
    const why = item.choices.map(c => `- ${label(c.id)}: ${item.option_explanations[c.id].explanation}`).join('\n');
    const calc = item.calc ? `\n**Calculation check:** \`${JSON.stringify(item.calc)}\`\n` : '';
    return `### ${item.id} · Part ${item.part} · ${item.subcategory}

*${item.topic} — ${item.subtopic} · ${item.cj_step} · ${item.difficulty} · ${item.type === 'sata' ? 'select all that apply' : 'single answer'}*

${item.prompt}

${opts}

**Rationale:** ${item.rationale}
${calc}
**Why each option:**
${why}

Reviewer: ________  Decision: ☐ Approve  ☐ Changes requested  Reference added: ☐

---
`;
  }).join('\n');
  return head + body;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const dir = new URL('../diagnostic-content/', import.meta.url);
  await writeFile(new URL('parts-b-d.import.sql', dir), buildImportSql(), 'utf8');
  await writeFile(new URL('PARTS_B_D_REVIEW_SHEET.md', dir), buildReviewSheet(), 'utf8');
  console.log(`Wrote ${ITEMS.length} draft questions to diagnostic-content/parts-b-d.import.sql and PARTS_B_D_REVIEW_SHEET.md`);
}
